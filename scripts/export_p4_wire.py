"""Copy the closed P4 wire declarations without importing service applications."""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DC = ROOT / "services/datacopilot/backend/app"
TARGET = ROOT / "services/harness/backend/src/app/adapters/analytics_dto.py"


def declarations(path, names):
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source)
    result = []
    for node in tree.body:
        name = getattr(node, "name", None)
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            name = (
                node.targets[0].id if isinstance(node, ast.Assign) else node.target.id
            )
        if name in names:
            if isinstance(node, ast.ClassDef):
                for child in [node, *node.body]:
                    if (
                        isinstance(child, (ast.ClassDef, ast.FunctionDef))
                        and ast.get_docstring(child) is None
                    ):
                        child.body.insert(
                            0, ast.Expr(ast.Constant(f"P4 {child.name} wire contract."))
                        )
                ast.fix_missing_locations(node)
                result.append(ast.unparse(node))
            else:
                result.append(ast.get_source_segment(source, node))
    return "\n\n".join(result)


def wire_source():
    header = '''"""P4 static wire snapshot; generated by scripts/export_p4_wire.py."""
from enum import StrEnum
from typing import Annotated, Literal
from pydantic import (
    BaseModel, ConfigDict, Field, StrictBool, StrictInt, StrictStr,
    field_validator, model_validator,
)

class BusinessAnalyticsModel(BaseModel):
    """Closed immutable wire metadata."""
    model_config = ConfigDict(extra="forbid", frozen=True, str_strip_whitespace=True)

SafeIdentity = str
TenantIdentity = str
ContractName = str
ContractVersion = str
LogicalDatasetName = str
CatalogFingerprint = str
ContractSha256 = Annotated[str, Field(pattern=r"^[a-f0-9]{64}$")]
SQLEngine = Literal["hive", "mysql", "spark_sql", "clickhouse"]
BusinessFieldClassification = Literal["public", "internal", "confidential", "restricted"]
'''
    governed = declarations(
        DC / "application/business_analytics/governed_models.py",
        {
            "WatermarkKind",
            "SnapshotConsistency",
            "JsonScalar",
            "BusinessAnalyticsExecutionStatus",
            "BusinessDatasetSnapshotMetadata",
            "BusinessDataSnapshot",
            "GovernedResultColumn",
            "GovernedBusinessAnalyticsResult",
        },
    )
    managed = declarations(
        DC / "application/business_analytics/managed_models.py",
        {
            "ManagedSQLReferencedField",
            "ManagedTokenUsage",
        },
    )
    report = declarations(
        DC / "application/demo_reports/service.py", {"ReportId", "ReportView"}
    )
    source = declarations(
        ROOT / "services/supportops/app/demo/exports.py", {"ExportView"}
    )
    return (
        header
        + "\n"
        + managed
        + "\n\n"
        + governed
        + "\n\n"
        + report
        + "\n\n"
        + source
        + "\n"
    )


if __name__ == "__main__":
    TARGET.write_text(wire_source(), encoding="utf-8")
